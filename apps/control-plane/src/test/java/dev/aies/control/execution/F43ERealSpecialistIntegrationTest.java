package dev.aies.control.execution;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.sun.net.httpserver.HttpServer;
import dev.aies.control.communication.CommunicationStore;
import io.vertx.core.Vertx;
import io.vertx.core.json.JsonObject;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import java.net.InetSocketAddress;
import java.net.http.HttpClient;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import static org.junit.jupiter.api.Assertions.*;

/** F4.3-E: real HTTP adapter, real local Event Bus and durable SQLite; HTTP is a deterministic fixture, NOT Ollama. */
class F43ERealSpecialistIntegrationTest {
    @TempDir Path root;

    @Test void actualAdapterReplyStagesCanonicalEvidenceAndSurvivesReopen() throws Exception {
        AtomicInteger calls = new AtomicInteger();
        HttpServer http = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        http.createContext("/api/generate", exchange -> {
            calls.incrementAndGet();
            byte[] body = "{\"response\":\"# Generated by test HTTP fixture\"}".getBytes(StandardCharsets.UTF_8);
            exchange.getRequestBody().readAllBytes();
            exchange.getResponseHeaders().set("Content-Type", "application/json");
            exchange.sendResponseHeaders(200, body.length);
            try (var out = exchange.getResponseBody()) {out.write(body);}
        });
        http.start();
        Vertx vertx = Vertx.vertx();
        ObjectMapper mapper = new ObjectMapper();
        try {
            var adapter = new OllamaSpecialistExecutor(HttpClient.newHttpClient(), mapper,
                "http://127.0.0.1:" + http.getAddress().getPort(), "qwen3:4b", 10);
            var consumer = vertx.eventBus().<JsonObject>localConsumer(ExecutionWorkerEngine.EXECUTE, message ->
                vertx.<JsonObject>executeBlocking(() -> adapter.execute(message.body()), false)
                    .onSuccess(message::reply).onFailure(error -> message.fail(503, "Adapter failure")));
            java.util.concurrent.CompletableFuture<Void> ready = new java.util.concurrent.CompletableFuture<>(); consumer.completionHandler(ar -> { if (ar.succeeded()) ready.complete(null); else ready.completeExceptionally(ar.cause()); }); ready.get(5, TimeUnit.SECONDS);
            try (var handoff = new ExecutionHandoffStore(root.resolve("execution-handoff.sqlite"), mapper)) {
                assertTrue(handoff.importPlan(ExecutionGraphTest.plan(ExecutionGraphTest.task("a"))));
            }
            var worker = new ExecutionWorkerEngine(vertx, mapper, root, 3, 60, 15);
            JsonObject result = worker.runOne("wf-execution");
            assertEquals("EVIDENCE_PENDING_VERIFICATION", result.getString("status"), result.encodePrettily());
            assertEquals(1, calls.get());
            String id = result.getString("artifactRecordId");
            assertNotNull(id);
            try (var handoff = new ExecutionHandoffStore(root.resolve("execution-handoff.sqlite"), mapper);
                 var communication = new CommunicationStore(root.resolve("communication.sqlite"), mapper)) {
                assertEquals("EVIDENCE_PENDING", handoff.list("wf-execution").getFirst().status());
                assertNotNull(ExecutionEvidenceVerifier.verify(communication, "wf-execution", "a",
                    "artifact://communication/" + id));
                assertTrue(worker.runOne("wf-execution").getBoolean("claimed") == false);
                assertEquals(1, calls.get(), "No duplicate inference while evidence is pending");
            }
            assertEquals("INCOMPLETE", new ExecutionAcceptanceManifest(root, mapper)
                .inspect("wf-execution").acceptanceStatus(), "Unreviewed model output must never be accepted");
        } finally {
            vertx.close().toCompletionStage().toCompletableFuture().get(10, TimeUnit.SECONDS);
            http.stop(0);
        }
    }
}
